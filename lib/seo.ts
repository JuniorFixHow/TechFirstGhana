export const absoluteUrl = (path = "/") => `${siteUrl}${path === "/" ? "" : path}`;

/** Normalises a social link that may be missing its protocol. */
const withProtocol = (url: string) => (url.startsWith("http") ? url : `https://${url.replace(/^\/+/, "")}`);

export const socialProfiles = [brand.linkedin, brand.instagram, brand.tiktok].map((url) =>
  withProtocol(url).split("?")[0]
);

type PageSeo = {
  title: string;
  description: string;
  path: string;
  keywords?: string[];
};

/** Builds per page metadata with a canonical URL and matching social tags. */
export function pageMetadata({ title, description, path, keywords }: PageSeo): Metadata {
  return {
    title,
    description,
    keywords: keywords ? [...keywords, ...siteConfig.keywords.slice(0, 3)] : undefined,
    alternates: { canonical: path },
    openGraph: {
      title: `${title} | ${siteConfig.name}`,
      description,
      url: path,
      siteName: siteConfig.name,
      locale: siteConfig.locale,
      type: "website",
      images: [shareImage],
    },
    twitter: {
      card: "summary_large_image",
      title: `${title} | ${siteConfig.name}`,
      description,
      images: [shareImage.url],
    },
  };
}


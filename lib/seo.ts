export function breadcrumbJsonLd(path: string): JsonLdObject {
  const page = navItems.find((n) => n.href === path);
  const items: JsonLdObject[] = [
    { "@type": "ListItem", position: 1, name: "Home", item: siteUrl },
  ];
  if (page && path !== "/") {
    items.push({ "@type": "ListItem", position: 2, name: page.label, item: absoluteUrl(path) });
  }
  return { "@context": "https://schema.org", "@type": "BreadcrumbList", itemListElement: items };
}

export function webPageJsonLd(
  type: "WebPage" | "AboutPage" | "ContactPage" | "CollectionPage",
  { title, description, path }: PageSeo
): JsonLdObject {
  return {
    "@context": "https://schema.org",
    "@type": type,
    "@id": `${absoluteUrl(path)}#webpage`,
    url: absoluteUrl(path),
    name: `${title} | ${brand.name}`,
    description,
    isPartOf: { "@id": websiteId },
    about: { "@id": orgId },
    inLanguage: "en",
  };
}

